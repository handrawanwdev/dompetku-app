function buildQuotes(source: CategorySource): string[] {
  const combos: string[] = [];
  for (const insight of source.insights) {
    for (const action of source.actions) {
      combos.push(`${insight} ${action}`);
    }
  }
  return combos.slice(0, source.count);
}

/** Lazily built on first access — 7000 short string concatenations, negligible cost. */
let cache: Record<QuoteCategory, string[]> | null = null;

function getBank(): Record<QuoteCategory, string[]> {
  if (!cache) {
    cache = Object.fromEntries(
      (Object.keys(SOURCES) as QuoteCategory[]).map((cat) => [cat, buildQuotes(SOURCES[cat])]),
    ) as Record<QuoteCategory, string[]>;
  }
  return cache;
}

export function getQuotesForCategory(category: QuoteCategory): string[] {
  return getBank()[category];
}

export function getRandomQuote(category: QuoteCategory): string {
  const quotes = getQuotesForCategory(category);
  return quotes[Math.floor(Math.random() * quotes.length)];
}

/** Total quote count across all categories — should always be exactly 7000 (1000 × 7). */
export function getTotalQuoteCount(): number {
  return (Object.keys(SOURCES) as QuoteCategory[]).reduce((s, c) => s + SOURCES[c].count, 0);
}
