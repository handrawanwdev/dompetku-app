import Realm, { ObjectSchema } from 'realm';

export class IncomeModel extends Realm.Object<IncomeModel> {
  _id!: Realm.BSON.ObjectId;
  date!: string;
  category!: string;
  amount!: number;
  note!: string;
  allocationDebt!: number;
  allocationSavings!: number;
  allocationCash!: number;
  /** DebtModel._id (hex) that received allocationDebt, if any */
  allocationDebtId!: string;
  /** SavingModel._id (hex) that received allocationSavings, if any */
  allocationSavingId!: string;
  /** True for synthetic rows (e.g. Tarik Tabungan) that just move money between
   * pockets rather than represent real income — excluded from ratio calcs. */
  isInternal!: boolean;
  /** 'active' | 'passive' — passive covers manual dividend entries and rows
   * auto-generated by PassiveIncomeScheduler from a recurring PassiveIncome rule. */
  type!: string;
  /** AccountModel._id (hex) kantong tujuan. '' = belum ditentukan. */
  accountId!: string;
  /** Sumber baris otomatis: 'investment:<id>' / 'asset:<id>' = hasil jual,
   * 'debt:<id>' = uang pinjaman masuk. '' = dicatat manual. */
  ref!: string;
  createdAt!: Date;

  static schema: ObjectSchema = {
    name: 'Income',
    primaryKey: '_id',
    properties: {
      _id: { type: 'objectId', default: () => new Realm.BSON.ObjectId() },
      date: 'string',
      category: 'string',
      amount: 'double',
      note: { type: 'string', default: '' },
      allocationDebt: { type: 'double', default: 0 },
      allocationSavings: { type: 'double', default: 0 },
      allocationCash: { type: 'double', default: 0 },
      allocationDebtId: { type: 'string', default: '' },
      allocationSavingId: { type: 'string', default: '' },
      isInternal: { type: 'bool', default: false },
      type: { type: 'string', default: 'active' },
      accountId: { type: 'string', default: '' },
      ref: { type: 'string', default: '' },
      createdAt: { type: 'date', default: () => new Date() },
    },
  };
}
